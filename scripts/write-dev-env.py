#!/usr/bin/env python3
"""Generate dev/data/dev.env with fresh random development credentials (idempotent).

Usage: write-dev-env.py <target-file> <postgres-port>
An existing file is never overwritten, so credentials stay stable between runs.
"""

import os
import secrets
import sys
from pathlib import Path


def main() -> int:
    target = Path(sys.argv[1])
    db_port = sys.argv[2]
    if target.exists():
        return 0
    root = Path(__file__).resolve().parents[1]
    db_password = secrets.token_urlsafe(24)
    db_url = f"postgresql+psycopg://rushbase:{db_password}@127.0.0.1:{db_port}/rushbase"
    values = {
        "RUSHBASE_DEV_DB_PASSWORD": db_password,
        "RUSHBASE_DEV_SMB_PASSWORD": secrets.token_urlsafe(24),
        "RUSHBASE_DEV_UID": str(os.getuid()),
        "RUSHBASE_DEV_GID": str(os.getgid()),
        "RUSHBASE_SECRET_KEY": secrets.token_urlsafe(48),
        "RUSHBASE_DATABASE_URL": db_url,
        "RUSHBASE_TEST_DATABASE_URL": db_url,
        "RUSHBASE_HOST": "127.0.0.1",
        "RUSHBASE_PORT": "18080",
        "RUSHBASE_LIBRARY_ROOT": str(root / "dev" / "library"),
    }
    target.parent.mkdir(parents=True, exist_ok=True)
    fd = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        handle.write("# Generated by scripts/write-dev-env.py - local development only.\n")
        handle.writelines(f"{key}={value}\n" for key, value in values.items())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
