"""The pinned lock files: ``binaries.lock.json`` and ``models.lock.json``.

Downloads are verified against these files (never against a live API) and abort on mismatch.
They are generated by ``worker/scripts/update-lock.py`` and reviewed as diffs.
"""

import json
from functools import lru_cache
from pathlib import Path
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict

DATA_DIR = Path(__file__).resolve().parent.parent / "data"
SOURCE_DIR = Path(__file__).resolve().parents[3]
"""``worker/`` in a source checkout (the wheel carries copies in ``rushbase_worker/data``)."""

ModelKind = Literal["vlm", "asr", "embed-image", "embed-text", "audio-events", "vad"]


class _Frozen(BaseModel):
    model_config = ConfigDict(frozen=True, extra="ignore")


class ModelFile(_Frozen):
    role: str
    repo: str
    filename: str
    revision: str
    size: int
    sha256: str

    @property
    def local_name(self) -> str:
        """File name inside the model directory."""
        return self.filename.rsplit("/", 1)[-1]

    @property
    def url(self) -> str:
        """Immutable download URL (pinned commit)."""
        return f"https://huggingface.co/{self.repo}/resolve/{self.revision}/{self.filename}"


class ModelSpec(_Frozen):
    id: str = ""
    kind: ModelKind
    display: str
    license: str
    files: tuple[ModelFile, ...]

    @property
    def size(self) -> int:
        return sum(f.size for f in self.files)

    @property
    def revision(self) -> str:
        """Revision of the first file (all files of a model are pinned together)."""
        return self.files[0].revision

    def file(self, role: str) -> ModelFile:
        for file in self.files:
            if file.role == role:
                return file
        raise KeyError(f"{self.id} has no file with role {role!r}")


class ModelsLock(_Frozen):
    models: dict[str, ModelSpec]

    def get(self, model_id: str) -> ModelSpec:
        try:
            return self.models[model_id].model_copy(update={"id": model_id})
        except KeyError:
            raise KeyError(f"unknown model {model_id!r}; known: {', '.join(self.models)}") from None

    def all(self) -> list[ModelSpec]:
        return [self.get(model_id) for model_id in self.models]


class Asset(_Frozen):
    """One downloadable archive."""

    name: str
    url: str
    sha256: str
    size: int


class LlamaPlatform(Asset):
    runtime_bundle: Asset | None = None


class LlamaLock(_Frozen):
    tag: str
    platforms: dict[str, LlamaPlatform]


class WhisperFallback(Asset):
    release: str


class WhisperLock(_Frozen):
    tag: str
    platforms: dict[str, Asset] = {}
    upstream_cpu_fallback: WhisperFallback | None = None


class BinariesLock(_Frozen):
    llama: LlamaLock
    whisper: WhisperLock


def _read(name: str) -> dict[str, Any]:
    for base in (DATA_DIR, SOURCE_DIR):
        path = base / name
        if path.is_file():
            loaded: dict[str, Any] = json.loads(path.read_text())
            return loaded
    raise FileNotFoundError(f"{name} not found next to the worker package")


@lru_cache(maxsize=1)
def load_models_lock() -> ModelsLock:
    """The pinned models."""
    return ModelsLock.model_validate(_read("models.lock.json"))


@lru_cache(maxsize=1)
def load_binaries_lock() -> BinariesLock:
    """The pinned inference binaries."""
    raw = _read("binaries.lock.json")
    return BinariesLock(
        llama=LlamaLock.model_validate(raw["llama.cpp"]),
        whisper=WhisperLock.model_validate(raw["whisper.cpp"]),
    )
